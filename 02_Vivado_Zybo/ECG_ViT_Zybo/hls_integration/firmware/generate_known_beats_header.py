"""Quantize ALL saved golden vectors into a firmware header (known_beats_data.h).

Reads  : 03_HW_SW_Validation/vitis_hls/z7_tiny_ecg_vit/golden_test_vectors.h
Writes : known_beats_data.h  (next to this script)

Values are raw signed Q6.10 integers (value * 1024, round-half-to-even,
saturated to 16 bits), the same conversion used by generate_demo_header.py.
It does not train or change the model and does not modify the golden file.
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
GOLDEN = (
    HERE.parents[3]
    / "03_HW_SW_Validation"
    / "vitis_hls"
    / "z7_tiny_ecg_vit"
    / "golden_test_vectors.h"
)
OUT = HERE / "known_beats_data.h"
CLASS_NAMES = "NSVFQ"


def read_rows(source: str, name: str) -> list[list[float]]:
    match = re.search(
        rf"static const float {name}\[[^;]*?=\s*\{{(.*?)\n\}};",
        source,
        flags=re.DOTALL,
    )
    if not match:
        raise RuntimeError(f"Could not find {name} in {GOLDEN}")
    rows = re.findall(r"\{([^{}]+)\}", match.group(1))
    return [[float(x.rstrip("f")) for x in re.findall(r"[-+0-9.eE]+f?", row)] for row in rows]


def read_ints(source: str, name: str) -> list[int]:
    match = re.search(
        rf"static const int {name}\[[^;]*?=\s*\{{(.*?)\}};",
        source,
        flags=re.DOTALL,
    )
    if not match:
        raise RuntimeError(f"Could not find {name} in {GOLDEN}")
    return [int(x) for x in re.findall(r"-?\d+", match.group(1))]


def q610(value: float) -> int:
    # Python round() is ties-to-even, matching the HLS AP_RND_CONV rounding.
    return max(-32768, min(32767, round(value * 1024)))


def wrap(values: list[int], per_line: int = 12) -> str:
    return ",\n    ".join(", ".join(str(v) for v in values[i : i + per_line]) for i in range(0, len(values), per_line))


def main() -> None:
    source = GOLDEN.read_text(encoding="utf-8")
    ecg = read_rows(source, "GOLDEN_ECG")
    rr = read_rows(source, "GOLDEN_RR")
    expected = read_ints(source, "GOLDEN_EXPECTED_CLASS")
    true_cls = read_ints(source, "GOLDEN_TRUE_CLASS")
    count = len(ecg)
    if not (len(rr) == len(expected) == len(true_cls) == count):
        raise RuntimeError("Golden arrays have different lengths")
    for i in range(count):
        if len(ecg[i]) != 198 or len(rr[i]) != 2:
            raise RuntimeError(f"Golden vector {i} must have 198 ECG and 2 RR values")

    lines = [
        "// Generated by generate_known_beats_header.py from golden_test_vectors.h.",
        "// Raw signed Q6.10 values. Do not edit by hand.",
        "#ifndef KNOWN_BEATS_DATA_H",
        "#define KNOWN_BEATS_DATA_H",
        "#include <stdint.h>",
        f"#define KNOWN_COUNT {count}u",
        f"static const int16_t known_ecg_q10[{count}][198] __attribute__((aligned(4))) = {{",
    ]
    for i in range(count):
        lines.append("  { // beat %d: true %s, checkpoint predicts %s" % (i, CLASS_NAMES[true_cls[i]], CLASS_NAMES[expected[i]]))
        lines.append("    " + wrap([q610(x) for x in ecg[i]]))
        lines.append("  }" + ("," if i + 1 < count else ""))
    lines.append("};")
    lines.append(f"static const int16_t known_rr_q10[{count}][2] __attribute__((aligned(4))) = {{")
    lines.append("    " + ",\n    ".join("{%d, %d}" % (q610(r[0]), q610(r[1])) for r in rr))
    lines.append("};")
    lines.append(f"static const uint8_t known_expected_class[{count}] = {{{', '.join(map(str, expected))}}};")
    lines.append(f"static const uint8_t known_true_class[{count}] = {{{', '.join(map(str, true_cls))}}};")
    lines.append("#endif")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} with {count} beats.")
    print("Expected LED sequence (checkpoint predictions): " + ", ".join(CLASS_NAMES[c] for c in expected))
    print("True labels of these beats:                      " + ", ".join(CLASS_NAMES[c] for c in true_cls))


if __name__ == "__main__":
    main()
