"""Generate C headers from the active TensorFlow checkpoint export.

Run this from the project root with the project's .venv Python. The generated
assets stay in this HLS project and are reproducible from the checked-in NPZs.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[3]
EXPORT_DIR = ROOT / "03_HW_SW_Validation" / "model_export"
OUT_DIR = Path(__file__).resolve().parent


TENSOR_NAMES = {
    "conv2d/kernel": "W_CONV",
    "conv2d/bias": "B_CONV",
    "posembed_input/pos_embedding": "W_POS",
    "layer_normalization/gamma": "GAMMA_1",
    "layer_normalization/beta": "BETA_1",
    "multi_head_attention/query/kernel": "W_Q",
    "multi_head_attention/query/bias": "B_Q",
    "multi_head_attention/key/kernel": "W_K",
    "multi_head_attention/key/bias": "B_K",
    "multi_head_attention/value/kernel": "W_V",
    "multi_head_attention/value/bias": "B_V",
    "multi_head_attention/attention_output/kernel": "W_O",
    "multi_head_attention/attention_output/bias": "B_O",
    "layer_normalization_1/gamma": "GAMMA_2",
    "layer_normalization_1/beta": "BETA_2",
    "dense/kernel": "W_FF1",
    "dense/bias": "B_FF1",
    "dense_1/kernel": "W_FF2",
    "dense_1/bias": "B_FF2",
    "encoder_norm/gamma": "GAMMA_OUT",
    "encoder_norm/beta": "BETA_OUT",
    "dense_2/kernel": "W_RR",
    "head/kernel": "W_HEAD",
    "head/bias": "B_HEAD",
}


def c_float(value: float) -> str:
    text = f"{float(np.float32(value)):.9g}"
    if "." not in text and "e" not in text.lower():
        text += ".0"
    return text + "f"


def write_tensor_header() -> None:
    npz_path = EXPORT_DIR / "active_model_weights_fp32.npz"
    manifest_path = EXPORT_DIR / "active_model_weights_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest["parameter_count"] != 6643:
        raise ValueError("Unexpected parameter count in active model manifest")
    if manifest["quantization"]["status"] != "not_quantized":
        raise ValueError("This HLS starter expects the FP32 export")

    with np.load(npz_path) as data:
        arrays: dict[str, np.ndarray] = {}
        for item in manifest["tensors"]:
            variable_name = item["variable_name"]
            if variable_name not in TENSOR_NAMES:
                continue  # Dropout and Concatenate layers have no weights.
            arrays[TENSOR_NAMES[variable_name]] = np.asarray(
                data[item["array_key"]], dtype=np.float32
            ).reshape(-1)

    if set(arrays) != set(TENSOR_NAMES.values()):
        missing = sorted(set(TENSOR_NAMES.values()) - set(arrays))
        raise ValueError(f"Weight export is incomplete: {missing}")

    lines = [
        "// Generated by generate_hls_assets.py from the active saved checkpoint.",
        "// Do not edit by hand; source is model_export/active_model_weights_fp32.npz.",
        "#ifndef ACTIVE_MODEL_WEIGHTS_H",
        "#define ACTIVE_MODEL_WEIGHTS_H",
        "",
    ]
    for name, array in arrays.items():
        lines.append(f"static const float {name}[{array.size}] = {{")
        values = [c_float(v) for v in array]
        for start in range(0, len(values), 8):
            lines.append("    " + ", ".join(values[start : start + 8]) + ",")
        lines.extend(["};", ""])
    lines.append("#endif  // ACTIVE_MODEL_WEIGHTS_H")
    (OUT_DIR / "active_model_weights.h").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


def write_golden_header() -> None:
    npz_path = EXPORT_DIR / "golden_fp32_samples.npz"
    with np.load(npz_path) as data:
        ecg = np.asarray(data["ecg_samples"], dtype=np.float32)
        rr = np.asarray(data["rr_features"], dtype=np.float32)
        expected = np.asarray(data["predicted_class_indices"], dtype=np.int32)
        truth = np.asarray(data["true_class_indices"], dtype=np.int32)
    if ecg.shape != (9, 198) or rr.shape != (9, 2):
        raise ValueError(f"Unexpected golden-vector shapes: {ecg.shape}, {rr.shape}")

    lines = [
        "// Generated from model_export/golden_fp32_samples.npz.",
        "#ifndef GOLDEN_TEST_VECTORS_H",
        "#define GOLDEN_TEST_VECTORS_H",
        "#define GOLDEN_COUNT 9",
        "static const float GOLDEN_ECG[GOLDEN_COUNT][198] = {",
    ]
    for row in ecg:
        lines.append("    {" + ", ".join(c_float(v) for v in row) + "},")
    lines.append("};")
    lines.append("static const float GOLDEN_RR[GOLDEN_COUNT][2] = {")
    lines.extend(
        "    {" + ", ".join(c_float(v) for v in row) + "}," for row in rr
    )
    lines.extend(
        [
            "};",
            "static const int GOLDEN_EXPECTED_CLASS[GOLDEN_COUNT] = {",
            "    " + ", ".join(str(int(v)) for v in expected),
            "};",
            "static const int GOLDEN_TRUE_CLASS[GOLDEN_COUNT] = {",
            "    " + ", ".join(str(int(v)) for v in truth),
            "};",
            "#endif  // GOLDEN_TEST_VECTORS_H",
        ]
    )
    (OUT_DIR / "golden_test_vectors.h").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    write_tensor_header()
    write_golden_header()
    print(f"Generated HLS weights and golden vectors in: {OUT_DIR}")
